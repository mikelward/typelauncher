package app.typelauncher

import java.io.File
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The Google Play catalog as test data for the rules (maintainer,
 * 2026-11-22: "the catalog is the test data that proves whether rules have
 * any false positives"). Every app the crawl kept is checked against
 * [knownAppCategory], and the shipped catalog is checked to hold exactly the
 * apps the rules leave out, games aside.
 */
class CatalogRulesTest {
    private val catalog: Map<String, String> = parsePlayCatalog(resource("play-catalog.tsv"))

    private val exceptions: List<Triple<String, String, String>> = resource("catalog-rule-exceptions.tsv")
        .lines()
        .filter { it.isNotBlank() && !it.startsWith("#") }
        .map { line -> line.split("\t").let { (key, folder, why) -> Triple(key, folder, why) } }

    // Folders Google Play has a category for. A rule's folder outside these
    // refines Play's category rather than contradicting it.
    private val playFolders: Set<AppCategory> = catalog.values.mapNotNullTo(HashSet(), ::folderForPlayCategory)

    @Test
    fun theRules_agreeWithGooglePlay_exceptWhereTheExceptionsSayWhy() {
        val used = HashSet<Triple<String, String, String>>()
        val wrong = mutableListOf<String>()
        for ((packageName, playCategory) in catalog.toSortedMap()) {
            val rule = knownAppCategory(packageName) ?: continue
            val play = folderForPlayCategory(playCategory) ?: continue
            if (rule == play || rule !in playFolders) continue
            val excused = exceptions.filter { (key, folder) ->
                folder == rule.name && (key == packageName || key == playCategory)
            }
            if (excused.isEmpty()) wrong += "$packageName\t$playCategory\t${rule.name}" else used += excused
        }
        assertTrue(
            "The rules disagree with Google Play here. Fix the rule, or add an exception " +
                "to catalog-rule-exceptions.tsv saying why:\n" + wrong.joinToString("\n"),
            wrong.isEmpty(),
        )
        val stale = exceptions - used
        assertTrue(
            "No app needs these exceptions any more; remove them:\n" +
                stale.joinToString("\n") { (key, folder) -> "$key\t$folder" },
            stale.isEmpty(),
        )
    }

    @Test
    fun theShippedCatalog_holdsExactlyWhatTheRulesLeaveOut() {
        // Games declare themselves in their manifests, and an app the rules
        // place, or whose Play category maps to no folder, gains nothing.
        val wanted = catalog
            .filter { (packageName, category) ->
                !category.startsWith("GAME") &&
                    folderForPlayCategory(category) != null &&
                    knownAppCategory(packageName) == null
            }
            .toSortedMap()
        val regenerated = File("build/play_catalog.tsv").apply {
            writeText(
                "# Google Play category by package: the apps in the crawl's catalog that the\n" +
                    "# rules don't place, games aside. Generated by CatalogRulesTest.\n" +
                    wanted.entries.joinToString("") { (packageName, category) -> "$packageName\t$category\n" },
            )
        }
        val shipped = File("src/main/assets/play_catalog.tsv").takeIf { it.exists() }
            ?.let { parsePlayCatalog(it.readText()) }.orEmpty()
        assertTrue(
            "The shipped catalog is out of date: copy app/${regenerated.path} to app/src/main/assets/play_catalog.tsv",
            shipped == wanted,
        )
    }

    private fun resource(name: String): String =
        javaClass.classLoader!!.getResourceAsStream(name)!!.bufferedReader().use { it.readText() }
}
